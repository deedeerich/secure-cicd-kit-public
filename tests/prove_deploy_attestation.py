#!/usr/bin/env python3
"""V1 runs INSIDE both deploy reusables, before login: a direct caller cannot skip it.

WHY THIS EXISTS (ledger P-02 / L89, section 5 B-05; PROVENANCE_AND_ATTESTATION.md section 6.1-6.4)

    "A verification is a refusal." The kit verified the signed build provenance of the digest
    about to be deployed only in the STARTER TEMPLATE's verdict job. Any other caller of a deploy
    reusable -- a landing-zone pipeline, a mixed method, a repository that wrote its own workflow --
    deployed with no verification at all, and nothing in the deploy said so. PROV section 6.1 puts
    V1 in the deploy, before the point of no return.

WHAT IS BUILT
    Each deploy reusable carries a step `Verify the build-provenance attestation (V1, refuse
    before login)` GENERATED by scripts/inline_deploy_scripts.py from the verify-attestation
    composite's own script (one source; `--check` fails on drift), with a prelude that reads the
    job's digest and target and a suffix that refuses before login on any route other than PROCEED
    or PROCEED_WITH_ADVISORY. Inputs: attestation_signer_workflow, attestation_rung (default run;
    empty reads as run, never weaker), attestations_available. The job holds attestations: read.
    The posture step carries V1's route; outcome.json records it, and a VERIFIED attestation is
    credited as "exact artefact identity established" for promotion.

WHAT IS RUN
    The V1 step of both reusables AS SHIPPED, under GitHub's shell, with `gh` SHIMMED to recorded
    answers (the same shapes tests/prove_attestation_verify.py uses), the job env resolved from
    stubbed inputs; then the posture step with V1's outcome; then the whole job against the stub
    cloud, where the repository is not public and the plan offers nothing (V1 held, gh never
    called) and the deploy proceeds with the hold recorded.

CASES (docs/PROOF_RULE.md)
    allowed           verified -> proceeds, PROCEED; held by the plan -> proceeds, gh never called
    attack            contradicted (bad signature, wrong subject) -> refused before login, BLOCKED
    missing-evidence  absent at run -> refused, DECISION_REQUIRED; network -> refused,
                      EVIDENCE_UNTRUSTED; no signer pinned on an armed repository -> refused, gh
                      never called
    recovery          absent at crawl -> proceeds with the advisory; an empty rung reads as run
    static            the step precedes azure/login and follows the gate verdict; inputs; the
                      permission; in-repo callers grant it

EXIT 0 proven   1 a case decided wrongly   2 could not be checked (UNKNOWN, never PASS)
"""
import os
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import _step_harness as H  # noqa: E402
import _workflow_runner as W  # noqa: E402

STEP = 'Verify the build-provenance attestation (V1, refuse before login)'
VERDICT = 'Gate verdict (refuse before login)'
WFS = ['.github/workflows/reusable-deploy-appservice.yml',
       '.github/workflows/reusable-deploy-containerapp.yml']
TEMPLATE = 'templates/build-deploy.yml'
DIGEST = 'sha256:' + '8' * 64
OTHER = '9' * 64
INPUTS = ('attestation_signer_workflow', 'attestation_rung', 'attestations_available')

GH = r'''
echo "$*" >> "$SHIM_CALLS"
case "$SHIM_MODE" in
  verified) printf '[{"verificationResult":{"statement":{"subject":[{"name":"x","digest":{"sha256":"%s"}}]}}}]\n' "${SHIM_DIGEST#sha256:}" ;;
  wrongsubject) printf '[{"verificationResult":{"statement":{"subject":[{"name":"x","digest":{"sha256":"%s"}}]}}}]\n' "$SHIM_OTHER" ;;
  absent) echo "Error: no attestations found for subject" >&2; exit 1 ;;
  badsig) echo "Error: failed to verify signature: certificate identity does not match expected signer workflow" >&2; exit 1 ;;
  network) echo "Error: dial tcp: lookup api.github.com: no such host" >&2; exit 1 ;;
  *) echo "gh shim: unknown mode" >&2; exit 64 ;;
esac
'''


def static(bad):
    import yaml  # noqa: F401
    for wf in WFS:
        doc = H.load(wf)
        on = doc.get('on', doc.get(True)) or {}
        ins = (on.get('workflow_call') or {}).get('inputs') or {}
        for i in INPUTS:
            if i not in ins:
                bad.append('%s: no input %s' % (wf, i))
        if str((doc.get('permissions') or {}).get('attestations')) != 'read':
            bad.append('%s: the workflow does not request attestations: read; gh cannot read the '
                       'attestation it must verify' % wf)
        steps = doc['jobs']['deploy']['steps']
        names = [s.get('name') for s in steps]
        if STEP not in names:
            bad.append('%s: no step %r -- a direct caller deploys with no verification' % (wf, STEP))
            continue
        vi = names.index(STEP)
        login = [i for i, s in enumerate(steps) if 'azure/login' in str(s.get('uses', ''))]
        if not login or login[0] < vi or names.index(VERDICT) > vi:
            bad.append('%s: V1 must follow the gate verdict and precede azure/login' % wf)
        posture = [s for s in steps if s.get('id') == 'posture']
        if not posture or 'steps.attestation.outputs.routing_result' not in str(posture[0].get('env')):
            bad.append('%s: the posture step does not read the V1 route' % wf)
    t = H.load(TEMPLATE)
    dep = (t.get('jobs') or {}).get('deploy') or {}
    if str((dep.get('permissions') or {}).get('attestations')) != 'read':
        bad.append('template: the deploy job does not grant attestations: read (startup_failure)')
    if 'reusable-build-docker.yml' not in str((dep.get('with') or {}).get(
            'attestation_signer_workflow', '')):
        bad.append('template: the deploy does not pin the signer workflow')


def main():
    try:
        import yaml  # noqa: F401
    except ImportError:
        print('UNKNOWN: PyYAML unavailable.')
        return 2
    bash, why = H.usable_bash()
    if not bash:
        print('UNKNOWN: no usable bash (%s).' % why)
        return 2
    if not shutil.which('jq'):
        print('UNKNOWN: jq is required.')
        return 2
    bad = []
    static(bad)
    if bad:
        for b in bad:
            print('FAIL: %s' % b)
        return 1
    tmp = tempfile.mkdtemp(prefix='deploy-attestation-probe-')
    try:
        shims = os.path.join(tmp, 'shim')
        H.shim(shims, 'gh', GH)
        n = [0]
        for wf in WFS:
            short = os.path.basename(wf).replace('reusable-deploy-', '').replace('.yml', '')
            step = H.step(wf, 'deploy', STEP)
            posture = H.step(wf, 'deploy', 'posture')

            def run(mode, rung='run', visibility='public', available='false',
                    signer='org/kit/.github/workflows/reusable-build-docker.yml'):
                n[0] += 1
                ws = os.path.join(tmp, 'ws%d' % n[0])
                os.makedirs(ws)
                calls = os.path.join(ws, 'calls')
                ctx = {'inputs.image_digest': DIGEST, 'inputs.acr_login_server': 'reg.example',
                       'inputs.image_repository': 'team/app', 'github.repository': 'org/app',
                       'inputs.attestation_signer_workflow': signer,
                       'inputs.attestation_rung': rung,
                       'github.event.repository.visibility': visibility,
                       'inputs.attestations_available': available, 'github.token': 't'}
                env = {'SHIM_MODE': mode, 'SHIM_CALLS': calls, 'SHIM_DIGEST': DIGEST,
                       'SHIM_OTHER': OTHER}
                r = H.run(bash, step, ctx, ws, shims, env)
                return r, os.path.exists(calls)

            # (case, kwargs, must_proceed, outcome, route, gh_called)
            cases = [
                ('allowed-verified', dict(mode='verified'), True, 'ATTESTATION_VERIFIED',
                 'PROCEED', True),
                ('allowed-held', dict(mode='verified', visibility='private'), True,
                 'ATTESTATION_HELD_BY_PLAN', 'PROCEED_WITH_ADVISORY', False),
                ('attack-badsig', dict(mode='badsig'), False, 'ATTESTATION_CONTRADICTED',
                 'BLOCKED', True),
                ('attack-wrong-subject', dict(mode='wrongsubject'), False,
                 'ATTESTATION_CONTRADICTED', 'BLOCKED', True),
                ('missing-absent', dict(mode='absent'), False, 'ATTESTATION_ABSENT',
                 'DECISION_REQUIRED', True),
                ('missing-network', dict(mode='network'), False, 'ATTESTATION_NOT_ESTABLISHABLE',
                 'EVIDENCE_UNTRUSTED', True),
                ('missing-signer', dict(mode='verified', signer=''), False,
                 'ATTESTATION_NOT_ESTABLISHABLE', 'EVIDENCE_UNTRUSTED', False),
                ('recovery-crawl', dict(mode='absent', rung='crawl'), True, 'ATTESTATION_ABSENT',
                 'PROCEED_WITH_ADVISORY', True),
                ('recovery-empty-rung', dict(mode='absent', rung=''), False,
                 'ATTESTATION_ABSENT', 'DECISION_REQUIRED', True),
            ]
            for case, kw, must, outcome, route, called in cases:
                r, gh_called = run(**kw)
                o = r['outputs']
                print('  %-13s %-21s exit=%d outcome=%-30s routing=%-22s gh=%s'
                      % (short, case, r['rc'], o.get('outcome'), o.get('routing_result'),
                         gh_called))
                if (r['rc'] == 0) != must:
                    bad.append('%s %s: exit %d, want %s\n%s' % (short, case, r['rc'],
                                                                'proceed' if must else 'refusal',
                                                                r['log'][-400:]))
                if o.get('outcome') != outcome or o.get('routing_result') != route:
                    bad.append('%s %s: %s / %s, want %s / %s' % (
                        short, case, o.get('outcome'), o.get('routing_result'), outcome, route))
                if gh_called != called:
                    bad.append('%s %s: gh %s called' % (short, case, 'was' if gh_called else
                                                        'was not'))
                if not must and 'refused before login' not in r['log']:
                    bad.append('%s %s: refused without saying it was refused before login'
                               % (short, case))

            # posture: V1's route is carried, never weakened.
            base = {'inputs.routing_result': 'PROCEED', 'inputs.rollback_on_failure': 'true',
                    'inputs.slot': 'staging', 'inputs.swap_on_healthy': 'true',
                    'inputs.health_path': '/health', 'inputs.health_retries': '1',
                    'inputs.health_interval_seconds': '1', 'inputs.attestation_rung': 'run',
                    'steps.verdict.outcome': 'success', 'steps.bind.outcome': 'success',
                    'steps.verdict.outputs.version_gap_ruling': 'VERSION_GAP_NOT_ENGAGED',
                    'steps.tier.outcome': 'success', 'steps.capability.outcome': 'success',
                    'steps.capability.outputs.rollback_capability': 'AVAILABLE',
                    'steps.report.outcome': 'success', 'job.status': 'success',
                    'steps.report.outputs.deployment_outcome': 'DEPLOY_HEALTHY'}
            for case, extra, want in (
                    ('v1-held', {'steps.attestation.outcome': 'success',
                                 'steps.attestation.outputs.routing_result':
                                     'PROCEED_WITH_ADVISORY'}, 'PROCEED_WITH_ADVISORY'),
                    ('v1-verified', {'steps.attestation.outcome': 'success',
                                     'steps.attestation.outputs.routing_result': 'PROCEED'},
                     'PROCEED'),
                    ('v1-contradicted', {'steps.attestation.outcome': 'failure',
                                         'steps.attestation.outputs.routing_result': 'BLOCKED',
                                         'steps.report.outcome': 'failure', 'job.status': 'failure',
                                         'steps.report.outputs.deployment_outcome':
                                             'DEPLOY_REFUSED'}, 'BLOCKED'),
                    ('v1-absent', {'steps.attestation.outcome': 'failure',
                                   'steps.attestation.outputs.routing_result': 'DECISION_REQUIRED',
                                   'steps.report.outcome': 'failure', 'job.status': 'failure',
                                   'steps.report.outputs.deployment_outcome': 'DEPLOY_REFUSED'},
                     'DECISION_REQUIRED'),
                    ('v1-answered-nothing', {'steps.attestation.outcome': 'success',
                                             'steps.attestation.outputs.routing_result': ''},
                     'EVIDENCE_UNTRUSTED')):
                n[0] += 1
                ws = os.path.join(tmp, 'p%d' % n[0])
                os.makedirs(ws)
                p = H.run(bash, posture, dict(base, **extra), ws)
                got = p['outputs'].get('routing_result')
                print('  %-13s posture %-19s routing_result=%s' % (short, case, got))
                if got != want:
                    bad.append('%s posture %s: routing_result=%r, want %s\n%s'
                               % (short, case, got, want, p['log'][-300:]))

        # The whole job: a repository that is not public, on a plan with no attestations. V1 holds,
        # never calls gh, and the deploy goes ahead with the hold in outcome.json.
        for wf, inputs, state in (
                (W.D.CONTAINERAPP, dict(github_environment='env', routing_result='PROCEED',
                                        environment_tier='dev', resource_group='rg-a',
                                        containerapp_name='web', acr_login_server=W.REG,
                                        image_repository=W.REPO, image_digest=W.NEW,
                                        health_path='/health', health_retries=1,
                                        health_interval_seconds=0, rollback_on_failure=True),
                 W.containerapp_state()),
                (W.D.APPSERVICE, dict(github_environment='env', routing_result='PROCEED',
                                      environment_tier='dev', resource_group='rg-a',
                                      webapp_name='web', acr_login_server=W.REG,
                                      image_repository=W.REPO, image_digest=W.NEW,
                                      slot='staging', swap_on_healthy=True, health_path='/health',
                                      health_retries=1, health_interval_seconds=0,
                                      rollback_on_failure=True), W.appservice_state())):
            res, _final, calls = W.run_world(wf, inputs, state)
            o = res['evidence'].get('outcome.json') or {}
            att = o.get('attestation') or {}
            v1 = dict(res['order']).get(STEP)
            print('  %-13s job: V1 step %s, outcome=%s attestation=%s' % (
                os.path.basename(wf), v1, o.get('deployment_outcome'), att.get('outcome')))
            if v1 != 'success' or o.get('deployment_outcome') != 'DEPLOY_HEALTHY' or \
                    att.get('outcome') != 'ATTESTATION_HELD_BY_PLAN':
                bad.append('%s job: a plan-held V1 must let the deploy proceed with the hold '
                           'recorded in outcome.json (V1 %s, outcome %r, attestation %r)'
                           % (os.path.basename(wf), v1, o.get('deployment_outcome'), att))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if bad:
        for b in bad:
            print('FAIL: %s' % b)
        return 1
    print('PASS: both deploy reusables run V1 themselves, generated from the verify-attestation '
          'composite, after the gate verdict and before login: verified proceeds; contradicted, '
          'absent at run, unestablishable or an unpinned signer refuse before login with the route '
          'carried into the posture record; a plan hold proceeds, recorded, and never calls gh.')
    print('      STUBBED gh. Real `gh attestation verify` output for an ACR image is owed to a '
          'hosted run on a public repository (O-20).')
    return 0


if __name__ == '__main__':
    sys.exit(main())
