#!/usr/bin/env python3
"""The TEST-ONLY seed input can only ADD files to the scanned tree. Prove every refusal (KDEC-011).

WHY THIS EXISTS

    The three credential seeds and the negative control under tests/consumer-fixture/full/secrets/
    are generated by tests/make_fixture.py and never committed (0917493). A checkout therefore
    cannot carry them, and hosted run 38784374419 graded all four ABSENT: no scanner was ever shown
    them. KDEC-011 delivers them to the scan as a run artifact named by `test_only_seed_artifact`,
    an input that exists only so the kit can test itself.

    AN INPUT THAT PUTS FILES INTO THE SCANNED TREE IS A CONTROL SURFACE, EVEN THOUGH IT ADDS.
    A `.gitleaksignore` is a file; adding one would silence a finding. Overwriting a seeded file
    with a clean one would remove a signal while leaving the file in place. A path with `..` in
    it would write outside the tree. Each is an "add" in the narrow sense and a weakening in
    every sense that matters, so each is refused -- and this file runs the shipped steps against
    every one of them, because a refusal nobody has watched fire is a comment.

WHAT IS PROVEN
    static   the input is declared with an empty default and says TEST-ONLY in its own words;
             the three seed steps sit in `secret-scan` after the checkout and before the rules
             are written, in the order validate -> fetch -> place, every one guarded by the input
             being non-empty; the artifact name reaches the fetch through `with:` and every
             script through `env:`; and the input is read NOWHERE ELSE in the workflow, so an
             empty value leaves every scanner byte-for-byte as it was
    name     the validation step accepts a plain name and refuses traversal, separators, spaces,
             a leading dot, an empty value and an over-long value -- before anything is fetched
    place    the placement step, run as shipped under bash, against a scope holding files:
               adds       regular files land under the scope; placed=N is emitted
               overwrite  an entry that already exists in the scope: refused, and NOTHING placed
               hidden     a dotfile (.gitleaksignore): refused, nothing placed
               config     a scanner configuration (gitleaks*.toml, *.baseline): refused
               symlink    a non-regular entry: refused (where the host can create one)
               empty      an artifact holding no files: refused -- a delivery of nothing
               missing    the staging directory never arrived: refused
             and in EVERY scenario each file that was in the scope beforehand is still there,
             byte-identical: the input cannot remove and cannot change

EXIT
    0  every refusal fires and the add lands
    1  a refusal did not fire, the add did not land, or a pre-existing file was touched
    2  could not be checked (no bash, no PyYAML) -- UNKNOWN, never PASS
"""
import io
import os
import re
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import _step_harness as H  # noqa: E402

WF = '.github/workflows/reusable-security.yml'
JOB = 'secret-scan'
INPUT = 'test_only_seed_artifact'
VALIDATE = 'TEST-ONLY seeds — validate the artifact name before anything is fetched'
FETCH = 'TEST-ONLY seeds — fetch into a staging directory outside the tree'
PLACE = 'TEST-ONLY seeds — place into the scanned tree, add-only'
RULES = 'Write the Azure/Entra rules'
GUARD = "inputs.%s != ''" % INPUT


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    io.open(path, 'w', encoding='utf-8', newline='\n').write(text)


def snapshot(root):
    out = {}
    for dp, _dn, fn in os.walk(root):
        for f in fn:
            p = os.path.join(dp, f)
            out[os.path.relpath(p, root).replace('\\', '/')] = io.open(p, 'rb').read()
    return out


def static_checks(doc):
    bad = []
    ins = (doc.get('on', doc.get(True)) or {}).get('workflow_call', {}).get('inputs') or {}
    spec = ins.get(INPUT)
    if not isinstance(spec, dict):
        return ['the input `%s` is not declared under workflow_call.inputs' % INPUT]
    if spec.get('default', None) != '':
        bad.append('the input default is %r; it must be the empty string, so a caller who sets '
                   'nothing gets nothing' % (spec.get('default'),))
    if 'TEST-ONLY' not in str(spec.get('description') or ''):
        bad.append('the input description does not say TEST-ONLY')

    steps = doc['jobs'][JOB].get('steps') or []
    names = [s.get('name') or s.get('uses') or '' for s in steps]
    idx = {}
    for key in (VALIDATE, FETCH, PLACE, RULES):
        if key in names:
            idx[key] = names.index(key)
        else:
            bad.append('step %r is missing from job %s' % (key, JOB))
    if len(idx) == 4:
        checkout = next((i for i, s in enumerate(steps)
                         if str(s.get('uses') or '').startswith('actions/checkout@')), None)
        if checkout is None or not (checkout < idx[VALIDATE] < idx[FETCH] < idx[PLACE] < idx[RULES]):
            bad.append('the seed steps must run after the checkout and before the rules are written, '
                       'in the order validate -> fetch -> place (got checkout=%s, %s)'
                       % (checkout, sorted((v, k) for k, v in idx.items())))
        for key in (VALIDATE, FETCH, PLACE):
            s = steps[idx[key]]
            if str(s.get('if') or '').strip() != GUARD:
                bad.append('%r is guarded by %r; it must be exactly %r so an empty input runs '
                           'nothing' % (key, s.get('if'), GUARD))
            if isinstance(s.get('run'), str) and '${{' in s['run']:
                bad.append('%r interpolates an expression into its script; caller input must '
                           'arrive through env: (tests/lint_injection.py)' % key)
        fetch = steps[idx[FETCH]]
        if not str(fetch.get('uses') or '').startswith('actions/download-artifact@'):
            bad.append('the fetch step must be actions/download-artifact, got %r' % fetch.get('uses'))
        with_ = fetch.get('with') or {}
        if str(with_.get('name') or '').strip() != '${{ inputs.%s }}' % INPUT:
            bad.append('the fetch step must download exactly the named artifact, got name=%r'
                       % with_.get('name'))
        if 'runner.temp' not in str(with_.get('path') or ''):
            bad.append('the fetch must land OUTSIDE the tree (under runner.temp), got path=%r'
                       % with_.get('path'))

    # THE INPUT IS READ NOWHERE ELSE. Its whole effect is the three steps above; if any other
    # step, job-level key or expression read it, an empty value could change what a scanner
    # does. Walked structurally: every job's own keys, and every step that is not one of the
    # three, must be free of it.
    import yaml
    ref = re.compile(r'inputs\.%s\b' % INPUT)
    for jname, job in (doc.get('jobs') or {}).items():
        if not isinstance(job, dict):
            continue
        for key, val in job.items():
            if key == 'steps':
                continue
            if ref.search(yaml.safe_dump(val)):
                bad.append('job %s reads `inputs.%s` in its %r; the input may be read only by the '
                           'three seed steps' % (jname, INPUT, key))
        for s in (job.get('steps') or []):
            if not isinstance(s, dict):
                continue
            if jname == JOB and s.get('name') in (VALIDATE, FETCH, PLACE):
                continue
            if ref.search(yaml.safe_dump(s)):
                bad.append('step %r in job %s reads `inputs.%s`; the input may be read only by the '
                           'three seed steps' % (s.get('name') or s.get('uses'), jname, INPUT))
    text = io.open(os.path.join(H.ROOT, WF), encoding='utf-8').read()
    if not re.search(r'^\s*posture\s+%s\s+NOT_A_CONTROL_SURFACE\b' % INPUT, text, re.M):
        bad.append('the posture record does not enumerate `%s` (tests/check_weakening_record.py W1)'
                   % INPUT)
    return bad


def main():
    try:
        import yaml  # noqa: F401
    except ImportError:
        print('UNKNOWN: PyYAML unavailable.')
        return 2
    bash, why = H.usable_bash()
    if not bash:
        print('UNKNOWN: no usable bash (%s).' % why)
        return 2
    doc = H.load(WF)
    bad = static_checks(doc)
    for b in bad:
        print('FAIL (static): %s' % b)
    if bad:
        print('\nThe steps are not in place as specified; nothing dynamic can be proven yet.')
        return 1

    validate = H.step(WF, JOB, VALIDATE)
    place = H.step(WF, JOB, PLACE)
    tmp = tempfile.mkdtemp(prefix='test-only-seeds-')
    try:
        # ── artifact name ──────────────────────────────────────────────────────────────
        ws = os.path.join(tmp, 'name')
        os.makedirs(ws)
        cases = [('test-only-seeds-1', True), ('a.b_c-D9', True), ('../escape', False),
                 ('a/b', False), ('a b', False), ('.hidden', False), ('', False),
                 ('x' * 129, False), ('x' * 128, True), ('name;rm', False), ('$(id)', False)]
        for name, ok in cases:
            r = H.run(bash, validate, {'inputs.%s' % INPUT: name}, ws)
            got = r['rc'] == 0
            print('  name  %-22r %s' % (name[:20] + ('..' if len(name) > 20 else ''),
                                        'accepted' if got else 'refused'))
            if got != ok:
                bad.append('artifact name %r was %s; expected %s\n%s'
                           % (name, 'accepted' if got else 'refused',
                              'accepted' if ok else 'refused', r['log'][-300:]))

        # ── placement ─────────────────────────────────────────────────────────────────
        def scenario(name, seeds, pre=None, make_staging=True, symlink=None):
            ws = os.path.join(tmp, 'place-' + name)
            scope = os.path.join(ws, 'scope')
            staging = os.path.join(ws, 'rt', 'test-only-seeds')
            for rel, text in {'existing/x.txt': 'keep me\n', 'top.md': 'and me\n',
                              **(pre or {})}.items():
                write(os.path.join(scope, rel), text)
            if make_staging:
                os.makedirs(staging)
            for rel, text in seeds.items():
                write(os.path.join(staging, rel), text)
            if symlink:
                os.symlink(symlink[1], os.path.join(staging, symlink[0]))
            before = snapshot(scope)
            ctx = {'inputs.paths': 'scope', 'runner.temp': os.path.join(ws, 'rt').replace('\\', '/'),
                   'inputs.%s' % INPUT: 'test-only-seeds-1'}
            r = H.run(bash, place, ctx, ws)
            after = snapshot(scope)
            touched = [k for k, v in before.items() if after.get(k) != v]
            added = sorted(set(after) - set(before))
            return r, touched, added

        # adds: regular files land, nothing else changes, placed=N emitted
        r, touched, added = scenario('adds', {'secrets/a.txt': 'A\n', 'secrets/deep/b.env': 'B\n'})
        print('  place adds       rc=%d added=%s placed=%s' % (r['rc'], added, r['outputs'].get('placed')))
        if r['rc'] != 0 or added != ['secrets/a.txt', 'secrets/deep/b.env'] \
                or r['outputs'].get('placed') != '2':
            bad.append('adds: files did not land as expected (rc=%d, added=%s, placed=%r)\n%s'
                       % (r['rc'], added, r['outputs'].get('placed'), r['log'][-400:]))
        if touched:
            bad.append('adds: pre-existing files were changed: %s' % touched)
        if 'TEST-ONLY' not in r['summary']:
            bad.append('adds: the step summary does not say a TEST-ONLY input is in force')

        # (scenario, artifact contents, the refusal that must be the one that fired)
        refusals = [
            ('overwrite', {'existing/x.txt': 'replaced\n', 'secrets/new.txt': 'N\n'}, 'already exists'),
            ('hidden', {'.gitleaksignore': 'fp\n', 'secrets/new.txt': 'N\n'}, 'hidden entry'),
            ('hidden-nested', {'secrets/.gitleaksignore': 'fp\n', 'secrets/new.txt': 'N\n'}, 'hidden entry'),
            ('config', {'gitleaks-azure.toml': 'x\n', 'secrets/new.txt': 'N\n'}, 'scanner configuration'),
            ('baseline', {'secrets/x.baseline': 'x\n', 'secrets/new.txt': 'N\n'}, 'scanner configuration'),
            ('empty', {}, 'holds no files'),
        ]

        def refused(name, r, touched, added, why):
            print('  place %-13s rc=%d added=%s' % (name, r['rc'], added))
            if r['rc'] == 0:
                bad.append('%s: was NOT refused\n%s' % (name, r['log'][-400:]))
            elif why not in r['log']:
                bad.append('%s: refused, but not for the reason under test (%r absent from the '
                           'log)\n%s' % (name, why, r['log'][-400:]))
            if added:
                bad.append('%s: refused and yet placed %s -- a refusal must place nothing' % (name, added))
            if touched:
                bad.append('%s: pre-existing files were changed: %s' % (name, touched))

        for name, seeds, why in refusals:
            r, touched, added = scenario(name, seeds)
            refused(name, r, touched, added, why)

        r, touched, added = scenario('missing', {}, make_staging=False)
        refused('missing', r, touched, added, 'never arrived')

        try:
            r, touched, added = scenario('symlink', {'secrets/new.txt': 'N\n'},
                                         symlink=('secrets/link.txt', 'new.txt'))
            refused('symlink', r, touched, added, 'non-regular')
        except (OSError, NotImplementedError) as e:
            print('  place %-11s NOT CHECKED on this host (%s); the Linux self-test runs it'
                  % ('symlink', type(e).__name__))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if bad:
        for b in bad:
            print('FAIL: %s' % b)
        return 1
    print('PASS: the TEST-ONLY seed input adds regular files to the scanned tree and nothing else: '
          'an existing file, a hidden file, a scanner configuration, a non-regular entry, an empty '
          'or missing delivery and a malformed artifact name are each refused with nothing placed, '
          'and no pre-existing file is ever changed. Empty, it is read by nothing.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
