#!/usr/bin/env python3
"""Generate, or check, the copies of the deploy-contract scripts inlined into the deploy reusables.

WHY INLINED, AND WHY GENERATED
    A reusable workflow called cross-repo runs in the CALLER's workspace, so `scripts/...` is not
    there to run; `uses: ./` resolves against the caller too. The deploy reusables therefore
    carry the scripts as heredocs, materialised into $RUNNER_TEMP before first use -- the same
    choice reusable-security.yml made for the SARIF normaliser. Inlining means COPIES, and copies
    drift; this kit has shipped a fix applied to one copy and not the other. So the copies are
    generated from scripts/ and `--check` fails when any has diverged.

    The V1 attestation step is generated the same way (ledger P-02): its body is the
    verify-attestation composite's own script, between a prelude that reads the deploy job's digest
    and target and a suffix that refuses before login. One source for the five outcomes and the
    rung routing, so the template's V1 and the deploy's V1 cannot disagree.

USAGE
    python3 scripts/inline_deploy_scripts.py --write    regenerate the materialise and V1 steps
    python3 scripts/inline_deploy_scripts.py --check    exit 1 if any copy differs from its source

EXIT  0 in sync (or written)   1 drift found   2 could not be checked
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKFLOWS = ['.github/workflows/reusable-deploy-appservice.yml',
             '.github/workflows/reusable-deploy-containerapp.yml']
SCRIPTS = ['deploy_contract.py', 'derive_reversal_disposition.py', 'environment_protection.py',
           'rollback_hold.py', 'promotion.py', 'target_lease.py']
STEP_NAME = 'Materialise the deploy contract scripts'
INDENT = ' ' * 10
V1_ACTION = '.github/actions/verify-attestation/action.yml'
V1_STEP_NAME = 'Verify the build-provenance attestation (V1, refuse before login)'
V1_BEFORE = 'Azure login (OIDC)'   # inserted immediately before this step when absent
V1_HEAD = [
    '      - name: %s' % V1_STEP_NAME,
    '        id: attestation',
    '        # GENERATED by scripts/inline_deploy_scripts.py from %s -- do not' % V1_ACTION,
    '        # edit here; edit the composite and run `--write`. self-test fails on any drift.',
    '        # P-02 (PROVENANCE_AND_ATTESTATION.md section 6.1): V1 runs IN the deploy, before the',
    '        # point of no return, so no caller deploys an unverified digest by calling this',
    '        # reusable directly. Five outcomes routed by rung (section 6.3); a plan that offers no',
    '        # attestations is HELD (PROCEED_WITH_ADVISORY, IMPLEMENTATION_HELD, gh never called).',
    '        # tests/prove_deploy_attestation.py.',
    '        shell: bash',
    '        env:',
    '          REPO: ${{ github.repository }}',
    '          SIGNER: ${{ inputs.attestation_signer_workflow }}',
    '          RUNG: ${{ inputs.attestation_rung }}',
    '          VISIBILITY: ${{ github.event.repository.visibility }}',
    '          AVAILABLE: ${{ inputs.attestations_available }}',
    '          GH_TOKEN: ${{ github.token }}',
    '        run: |',
    '          # The digest and target this job deploys (after the bind step), never a second copy.',
    '          DIGEST="$IMAGE_DIGEST"',
    '          SUBJECT="${ACR_LOGIN_SERVER}/${IMAGE_REPOSITORY}"',
    '          RUNG="${RUNG:-run}"   # an empty rung reads as the strictest, never as a weaker one',
]
V1_TAIL = [
    '          # The deploy acts on the route: anything but PROCEED or PROCEED_WITH_ADVISORY stops here.',
    '          case "$route" in',
    '            PROCEED|PROCEED_WITH_ADVISORY)',
    '              echo "Attestation V1 ${outcome}: the deploy may proceed (${route})." ;;',
    '            *)',
    '              echo "::error title=Deploy refused before login (V1)::attestation ${outcome} at rung ${RUNG} routes ${route}. The digest about to be deployed is not shown to be the one the kit build signed. Nothing was deployed."',
    '              { echo "### Deploy refused before login (V1)"; echo ""',
    '                echo "${outcome} routes ${route} at rung ${RUNG}."; } >> "$GITHUB_STEP_SUMMARY"',
    '              exit 1 ;;',
    '          esac',
]


def delimiter(script):
    return 'kit_' + re.sub(r'[^a-z0-9]', '_', script.lower())


def source(script):
    return io.open(os.path.join(ROOT, 'scripts', script), encoding='utf-8').read().replace('\r\n', '\n')


def render_step():
    lines = ['      - name: %s' % STEP_NAME,
             '        # GENERATED by scripts/inline_deploy_scripts.py from scripts/ -- do not edit',
             '        # here; edit the script and run `--write`. self-test fails on any drift.',
             '        run: |',
             '          set -euo pipefail',
             '          mkdir -p "$RUNNER_TEMP/kit-deploy"']
    for s in SCRIPTS:
        tag = delimiter(s)
        lines.append('          cat > "$RUNNER_TEMP/kit-deploy/%s" <<\'%s\'' % (s, tag))
        for ln in source(s).rstrip('\n').split('\n'):
            lines.append((INDENT + ln) if ln.strip() else '')
        lines.append(INDENT + tag)
    return '\n'.join(lines) + '\n\n'


def v1_body():
    """The verify-attestation composite's script, as YAML gives it to the runner."""
    import yaml
    doc = yaml.safe_load(io.open(os.path.join(ROOT, V1_ACTION), encoding='utf-8').read())
    return doc['runs']['steps'][0]['run'].replace('\r\n', '\n')


def render_v1_step():
    lines = list(V1_HEAD)
    for ln in v1_body().rstrip('\n').split('\n'):
        lines.append((INDENT + ln) if ln.strip() else '')
    lines += V1_TAIL
    return '\n'.join(lines) + '\n\n'


def step_span(lines, name=STEP_NAME):
    """-> (start, end) line indexes of the named step, or None."""
    start = None
    for i, ln in enumerate(lines):
        if ln == '      - name: %s' % name:
            start = i
        elif start is not None and ln.startswith('      - name: '):
            return start, i
    return (start, len(lines)) if start is not None else None


def embedded(wf_text):
    """-> {script: body} as bash would write it, read through YAML like the runner does."""
    import yaml
    doc = yaml.safe_load(wf_text)
    for step in doc['jobs']['deploy']['steps']:
        if step.get('name') == STEP_NAME:
            run = step.get('run', '')
            out = {}
            for s in SCRIPTS:
                tag = delimiter(s)
                m = re.search(r"<<'%s'\n(.*?)\n%s\n" % (re.escape(tag), re.escape(tag)), run, re.S)
                out[s] = m.group(1) + '\n' if m else None
            return out
    return None


def main(argv):
    mode = '--write' if '--write' in argv else '--check'
    bad = []
    for wf in WORKFLOWS:
        path = os.path.join(ROOT, wf)
        raw = io.open(path, encoding='utf-8', newline='').read()
        crlf = '\r\n' in raw
        text = raw.replace('\r\n', '\n')
        if mode == '--write':
            lines = text.split('\n')
            span = step_span(lines)
            if span is None:
                print('%s: no %r step to regenerate. Add the step once by hand.' % (wf, STEP_NAME))
                return 2
            # The old step, its trailing blank line included, is replaced whole.
            new ='\n'.join(lines[:span[0]]) + '\n' + render_step() + '\n'.join(lines[span[1]:])
            # The V1 step: replaced whole, or inserted once immediately before the login.
            lines = new.split('\n')
            span = step_span(lines, V1_STEP_NAME) or step_span(lines, V1_BEFORE)
            if span is None:
                print('%s: neither a V1 step nor %r to place one before.' % (wf, V1_BEFORE))
                return 2
            end = span[1] if lines[span[0]] == '      - name: %s' % V1_STEP_NAME else span[0]
            new = '\n'.join(lines[:span[0]]) + '\n' + render_v1_step() + '\n'.join(lines[end:])
            if crlf:
                new = new.replace('\n', '\r\n')
            io.open(path, 'w', encoding='utf-8', newline='').write(new)
            print('%s: regenerated' % wf)
            continue
        try:
            got = embedded(text)
        except Exception as e:  # noqa: BLE001
            print('UNKNOWN: %s does not parse (%s).' % (wf, e))
            return 2
        if got is None:
            bad.append('%s: no %r step' % (wf, STEP_NAME))
            continue
        for s in SCRIPTS:
            if got.get(s) is None:
                bad.append('%s: %s is not embedded' % (wf, s))
            elif got[s] != source(s).rstrip('\n') + '\n':
                bad.append('%s: the embedded %s differs from scripts/%s' % (wf, s, s))
        lines = text.split('\n')
        span = step_span(lines, V1_STEP_NAME)
        if span is None:
            bad.append('%s: no %r step' % (wf, V1_STEP_NAME))
        elif '\n'.join(lines[span[0]:span[1]]) + '\n' != render_v1_step():
            bad.append('%s: the V1 step differs from %s (and its prelude and suffix)'
                       % (wf, V1_ACTION))
    if bad:
        for b in bad:
            print('DRIFT: ' + b)
        print('Run: python3 scripts/inline_deploy_scripts.py --write')
        return 1
    if mode == '--check':
        print('deploy-contract copies in sync: %d script(s) and the V1 step x %d workflow(s)'
              % (len(SCRIPTS), len(WORKFLOWS)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
