#!/usr/bin/env python3
"""The negative-test manifest: tell a known fixture seed from a new alert, and never by directory.

WHY THIS EXISTS (owner, 2026-11-18 / 2026-11-19)
    The kit's test fixtures are deliberately vulnerable: the scanners must be proven to DETECT them.
    So the kit repository raises alerts on them, and on 2026-11-19 eight Dependabot alerts on the
    fixtures were dismissed by hand (D:/handoffs record KIT_FIXTURE_ALERT_DISMISSALS_2026-11-19).
    A dismissal by DIRECTORY would also hide the next, real alert in that directory: a new advisory
    on a seeded package, a pin someone changed, or a new dependency added beside the seeds. The
    owner asked instead for a controlled manifest of every intentional fixture vulnerability with
    its expected finding, so a known seed is told apart from a new one and no directory is ignored
    wholesale. tests/negative-test-manifest.json is that manifest; this is its checker.

    The manifest BINDS the two registries that already existed instead of copying them:
    tests/consumer-fixture/SEED_PINS.json holds every fixture manifest's content hash and the named
    seed pins (tests/check_fixture_seed_pins.py), and EXPECTED_SIGNALS.json in each fixture holds
    what a consumer run must detect (tests/verify_expected_signals.py). Neither carries an advisory
    id, a rule id or a reason, which is what an alert must be matched against. `check` requires the
    three to agree, both ways, so none can drift from the others.

COMMANDS
    classify ALERTS.json   each alert -> {match: KNOWN_SEED | NEW, cause, seed}. Accepts a plain list
                           of {path, package or rule, version, advisory, tool}, a Dependabot alerts
                           API listing, or a code-scanning alerts API listing. KNOWN_SEED needs the
                           exact file, the exact package (or rule) AND version, AND an advisory id (or
                           alias) the manifest records for that seed. Anything else is NEW, with the
                           cause named. A directory is never a match. A Dependabot alert carries no
                           installed version, so the version is read from the file in this tree.
                           Exit 1 when any alert is NEW.
    check                  the tree (T1-T7 below). Exit 1 on any drift.
    propose TRIVY.json     print the seed entries a `trivy fs --format json` scan of the fixtures
                           implies, for a reviewer to compare with the manifest. Writes nothing:
                           the manifest is changed by a reviewed edit only.
    --self-test            the matcher's own cases.

TREE RULES (check)
    T1  every dependency seed's file exists and still pins exactly that package at that version
    T2  every exact pin in every dependency manifest under tests/ is a seed or a declared non-seed pin
        (a clean control, a compile-only dependency, a base image): nothing in a fixture tree is
        ignored because of where it sits
    T3  a dependency manifest under tests/ whose format this checker cannot read is a failure, never
        skipped
    T4  every EXPECTED_SIGNALS entry has a seed with the same file and signal, and every seed that
        names a signal is in EXPECTED_SIGNALS
    T5  every named seed pin in SEED_PINS.json is a seed here
    T6  a seed generated at run time (tests/make_fixture.py) is still generated by it; any other seed
        file exists
    T7  every dependency seed records at least one advisory id, or says why none is established

EXIT  0 held / every alert a known seed   1 drift / a NEW alert (each named)   2 could not be read
"""
import io
import json
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get('KIT_PROOF_ROOT') or os.path.dirname(HERE)
manifest_rel = 'tests/negative-test-manifest.json'
seed_pins_rel = 'tests/consumer-fixture/SEED_PINS.json'
generator_rel = 'tests/make_fixture.py'
scope_rel = 'tests'
# The same manifest file names tests/check_fixture_seed_pins.py holds, so the two see one population.
dep_manifest = re.compile(r'(?i)(^|/)(requirements[^/]*\.txt|composer\.(json|lock)|package(-lock)?\.json|'
                          r'yarn\.lock|pnpm-lock\.yaml|pom\.xml|build\.gradle(\.kts)?|go\.(mod|sum)|[^/]+\.csproj|'
                          r'packages\.(config|lock\.json)|gemfile(\.lock)?|cargo\.(toml|lock)|pipfile(\.lock)?|'
                          r'pyproject\.toml|dockerfile)$')
# go.sum holds hashes of what go.mod requires: never a pin of its own here.
not_pins = re.compile(r'(?i)(^|/)go\.sum$')


class Unreadable(Exception):
    pass


# ----------------------------------------------------------------------------- normalising
def norm_path(p):
    p = str(p or '').replace('\\', '/').strip()
    while p.startswith('./'):
        p = p[2:]
    return p.lstrip('/')


def norm_pkg(p):
    return str(p or '').strip().lower().replace('_', '-')


def norm_ver(v):
    v = str(v or '').strip()
    return v[1:] if re.match(r'^[vV]\d', v) else v


# ----------------------------------------------------------------------------- pin readers
def pins_of(root, rel):
    """-> [(package, version)] exact pins in one dependency manifest. Raises Unreadable for a format
    this reader does not know (T3): an unread manifest is never a manifest with no pins."""
    path = os.path.join(root, rel)
    text = io.open(path, encoding='utf-8', errors='replace').read()
    name = rel.rsplit('/', 1)[-1].lower()
    out = []
    try:
        if name.startswith('requirements') and name.endswith('.txt'):
            for line in text.splitlines():
                m = re.match(r'^\s*([A-Za-z0-9._-]+)\s*==\s*([^\s;#]+)', line)
                if m:
                    out.append((m.group(1), m.group(2)))
        elif name == 'package.json':
            doc = json.loads(text)
            for key in ('dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies'):
                for pkg, ver in (doc.get(key) or {}).items():
                    out.append((pkg, ver))
        elif name == 'package-lock.json':
            doc = json.loads(text)
            for key, val in (doc.get('packages') or {}).items():
                if key.startswith('node_modules/') and isinstance(val, dict):
                    out.append((key.rsplit('node_modules/', 1)[-1], val.get('version')))
        elif name == 'composer.json':
            doc = json.loads(text)
            for key in ('require', 'require-dev'):
                for pkg, ver in (doc.get(key) or {}).items():
                    if '/' in pkg:      # php and ext-* are platform requirements, not packages
                        out.append((pkg, ver))
        elif name == 'composer.lock':
            doc = json.loads(text)
            for p in (doc.get('packages') or []) + (doc.get('packages-dev') or []):
                out.append((p.get('name'), p.get('version')))
        elif name == 'pom.xml':
            tree = ET.fromstring(text)
            for dep in tree.iter():
                if dep.tag.split('}')[-1] != 'dependency':
                    continue
                f = dict((c.tag.split('}')[-1], (c.text or '').strip()) for c in dep)
                out.append(('%s:%s' % (f.get('groupId'), f.get('artifactId')), f.get('version')))
        elif name == 'go.mod':
            block = False
            for line in text.splitlines():
                s = line.split('//')[0].strip()
                if s.startswith('require ('):
                    block = True
                    continue
                if block and s == ')':
                    block = False
                    continue
                m = re.match(r'^(?:require\s+)?(\S+)\s+(v\S+)$', s) if (block or s.startswith('require ')) else None
                if m:
                    out.append((m.group(1), m.group(2)))
        elif name.endswith('.csproj'):
            tree = ET.fromstring(text)
            for el in tree.iter():
                if el.tag.split('}')[-1] == 'PackageReference':
                    out.append((el.get('Include'), el.get('Version')))
        elif name == 'dockerfile':
            stages = set()
            for line in text.splitlines():
                m = re.match(r'^\s*FROM\s+(?:--\S+\s+)*(\S+)(?:\s+AS\s+(\S+))?', line, re.I)
                if not m:
                    continue
                image = m.group(1)
                if m.group(2):
                    stages.add(m.group(2).lower())
                if image.lower() == 'scratch' or image.lower() in stages:
                    continue
                ref = image.split('@', 1)[0]
                img, _, tag = ref.rpartition(':') if ':' in ref.split('/')[-1] else (ref, '', '')
                out.append((img or ref, tag or 'latest'))
        else:
            raise Unreadable('%s: no pin reader for this manifest format' % rel)
    except (ValueError, ET.ParseError) as exc:
        raise Unreadable('%s: %s' % (rel, exc))
    return [(str(p), str(v)) for p, v in out if p and v]


def listed(root):
    """Every dependency manifest under tests/ (tracked, or on disk in an export without git)."""
    try:
        res = subprocess.run(['git', '-C', root, 'ls-files', '-z', '--', scope_rel], capture_output=True,
                             check=True, timeout=60)
        names = [n for n in res.stdout.decode('utf-8', 'replace').split('\0') if n]
    except Exception:                                 # noqa: BLE001 - an export without git
        names = []
        for dp, _dn, fns in os.walk(os.path.join(root, scope_rel)):
            for fn in fns:
                names.append(os.path.relpath(os.path.join(dp, fn), root).replace(os.sep, '/'))
    return sorted(n for n in names if dep_manifest.search(n) and not not_pins.search(n))


def load_manifest(root, rel=None):
    p = os.path.join(root, rel or manifest_rel)
    try:
        doc = json.load(io.open(p, encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise Unreadable('%s: %s' % (rel or manifest_rel, exc))
    if not isinstance(doc, dict) or not isinstance(doc.get('seeds'), list):
        raise Unreadable('%s has no seeds list' % (rel or manifest_rel))
    return doc


# ----------------------------------------------------------------------------- classify
def advisory_ids(seed):
    ids = set()
    for a in (seed.get('expected') or {}).get('advisories') or []:
        ids.add(str(a.get('id') or '').upper())
        for al in a.get('aliases') or []:
            ids.add(str(al).upper())
    ids.discard('')
    return ids


def normalise_alert(a):
    """-> {path, package, rule, version, advisory, tool, ref} from any accepted shape."""
    if isinstance(a, dict) and isinstance(a.get('dependency'), dict):            # Dependabot alert
        dep = a['dependency']
        adv = a.get('security_advisory') or {}
        return {'path': dep.get('manifest_path'), 'package': (dep.get('package') or {}).get('name'),
                'rule': None, 'version': None, 'tool': 'dependabot',
                'advisory': adv.get('ghsa_id') or adv.get('cve_id'), 'ref': a.get('number')}
    if isinstance(a, dict) and isinstance(a.get('rule'), dict):                  # code-scanning alert
        loc = ((a.get('most_recent_instance') or {}).get('location') or {})
        return {'path': loc.get('path'), 'package': None, 'rule': (a['rule'] or {}).get('id'),
                'version': None, 'tool': (a.get('tool') or {}).get('name'), 'advisory': None,
                'ref': a.get('number')}
    a = a if isinstance(a, dict) else {}
    return {'path': a.get('path'), 'package': a.get('package'), 'rule': a.get('rule'),
            'version': a.get('version'), 'tool': a.get('tool'), 'advisory': a.get('advisory'),
            'ref': a.get('ref')}


def classify_one(alert, seeds, tree_version=None):
    """-> {match, cause, seed}. Pure: tree_version(path, package) supplies a version the alert lacks."""
    al = normalise_alert(alert)
    path = norm_path(al['path'])
    out = {'alert': al, 'match': 'NEW', 'cause': None, 'seed': None}
    at_path = [s for s in seeds if norm_path(s.get('path')) == path]
    if not path or not at_path:
        out['cause'] = 'NOT_A_SEED'
        return out
    if al.get('package'):
        same = [s for s in at_path if s.get('kind') == 'dependency'
                and norm_pkg(s.get('package')) == norm_pkg(al['package'])]
        if not same:
            out['cause'] = 'NOT_A_SEED'
            return out
        ver = al.get('version')
        if not ver and tree_version:
            ver = tree_version(path, al['package'])
        if not ver:
            out['cause'] = 'VERSION_NOT_ESTABLISHED'
            return out
        hit = [s for s in same if norm_ver(s.get('version')) == norm_ver(ver)]
        if not hit:
            out['cause'] = 'PIN_CHANGED'
            out['seed'] = same[0].get('id')
            return out
        adv = str(al.get('advisory') or '').strip().upper()
        if not adv:
            out['cause'] = 'NO_ADVISORY_ID'
            out['seed'] = hit[0].get('id')
            return out
        for s in hit:
            if adv in advisory_ids(s):
                out.update(match='KNOWN_SEED', cause=None, seed=s.get('id'))
                return out
        out['cause'] = 'ADVISORY_NOT_IN_MANIFEST'
        out['seed'] = hit[0].get('id')
        return out
    rule = str(al.get('rule') or '').strip()
    if not rule:
        out['cause'] = 'NOT_A_SEED'
        return out
    tool = norm_pkg(al.get('tool'))
    cand = [s for s in at_path if s.get('kind') != 'dependency']
    if tool:
        # A SARIF driver name may carry a suffix ("Semgrep OSS"): the recorded tool must START it.
        cand = [s for s in cand if any(tool == norm_pkg(t) or tool.startswith(norm_pkg(t) + ' ')
                                       for t in (s.get('expected') or {}).get('tools') or [])]
    if not cand:
        out['cause'] = 'NOT_A_SEED'
        return out
    for s in cand:
        if rule in ((s.get('expected') or {}).get('rules') or []):
            out.update(match='KNOWN_SEED', cause=None, seed=s.get('id'))
            return out
    recorded = any((s.get('expected') or {}).get('rules') for s in cand)
    out['cause'] = 'RULE_NOT_IN_MANIFEST' if recorded else 'RULE_NOT_RECORDED'
    out['seed'] = cand[0].get('id')
    return out


def tree_versions(root):
    cache = {}

    def lookup(path, package):
        if path not in cache:
            try:
                cache[path] = pins_of(root, path) if os.path.isfile(os.path.join(root, path)) else []
            except Unreadable:
                cache[path] = []
        vs = [v for p, v in cache[path] if norm_pkg(p) == norm_pkg(package)]
        return vs[0] if len(set(vs)) == 1 else None
    return lookup


def read_alerts(path):
    """-> a flat list of alerts. Accepts one JSON document (a list, or {alerts|items: [...]}), the
    back-to-back arrays `gh api --paginate` prints, and the array of pages `--slurp` prints."""
    text = io.open(path, encoding='utf-8').read()
    dec, pos, docs = json.JSONDecoder(), 0, []
    while True:
        while pos < len(text) and text[pos].isspace():
            pos += 1
        if pos >= len(text):
            break
        doc, pos = dec.raw_decode(text, pos)
        docs.append(doc)
    out = []

    def flat(d):
        if isinstance(d, list):
            for x in d:
                flat(x) if isinstance(x, list) else out.append(x)
        elif isinstance(d, dict) and ('alerts' in d or 'items' in d):
            flat(d.get('alerts') or d.get('items') or [])
        elif isinstance(d, dict):
            out.append(d)
        else:
            raise Unreadable('%s: not a list of alerts' % path)
    for d in docs:
        flat(d)
    if not docs:
        raise Unreadable('%s is empty' % path)
    return out


def cmd_classify(root, alerts_path, as_json=False):
    try:
        man = load_manifest(root)
        raw = read_alerts(alerts_path)
    except (OSError, ValueError, Unreadable) as exc:
        print('UNKNOWN: %s' % exc)
        return 2
    if not isinstance(raw, list):
        print('UNKNOWN: the alerts file is not a list')
        return 2
    res = [classify_one(a, man['seeds'], tree_versions(root)) for a in raw]
    new = [r for r in res if r['match'] != 'KNOWN_SEED']
    if as_json:
        print(json.dumps({'outcome': 'NEW_ALERTS' if new else 'ALL_KNOWN_SEEDS', 'results': res}, indent=1))
    else:
        for r in res:
            a = r['alert']
            print('%-10s %-26s %s %s %s %s%s' % (
                r['match'], r['cause'] or '-', norm_path(a['path']), a.get('package') or a.get('rule') or '?',
                a.get('version') or '', a.get('advisory') or '', ('  (seed %s)' % r['seed']) if r['seed'] else ''))
        print('%d alert(s): %d KNOWN_SEED, %d NEW' % (len(res), len(res) - len(new), len(new)))
    return 1 if new else 0


# ----------------------------------------------------------------------------- check the tree
def expected_signals(root):
    """-> [(path, signal)] from every EXPECTED_SIGNALS.json under tests/consumer-fixture/."""
    out = []
    base = os.path.join(root, 'tests', 'consumer-fixture')
    for dp, _dn, fns in os.walk(base):
        if 'EXPECTED_SIGNALS.json' in fns:
            rel_dir = os.path.relpath(dp, root).replace(os.sep, '/')
            for e in json.load(io.open(os.path.join(dp, 'EXPECTED_SIGNALS.json'), encoding='utf-8')):
                out.append((rel_dir + '/' + e['path'], e['expected_signal']))
    return sorted(set(out))


def check_tree(root):
    """-> [failures]."""
    man = load_manifest(root)
    seeds = man['seeds']
    fails = []
    ids = [s.get('id') for s in seeds]
    for d in sorted(set(i for i in ids if ids.count(i) > 1)):
        fails.append('T0 seed id %s is used twice' % d)
    non = man.get('non_seed_pins') or []
    pins_cache = {}
    for rel in listed(root):
        try:
            pins_cache[rel] = pins_of(root, rel)
        except Unreadable as exc:
            fails.append('T3 %s -- a manifest that cannot be read is never treated as holding no seed' % exc)
    # T1, T6, T7
    gen = os.path.join(root, generator_rel)
    gen_text = io.open(gen, encoding='utf-8', errors='replace').read() if os.path.isfile(gen) else ''
    for s in seeds:
        p = norm_path(s.get('path'))
        if s.get('runtime_generated'):
            sub = p.split('tests/consumer-fixture/full/', 1)[-1]
            if ('add("%s"' % sub) not in gen_text:
                fails.append('T6 %s is listed as generated at run time, but %s no longer writes %s'
                             % (s.get('id'), generator_rel, sub))
            continue
        if not os.path.isfile(os.path.join(root, p)):
            fails.append('T6 %s names %s, which is not in the tree' % (s.get('id'), p))
            continue
        if s.get('kind') == 'dependency':
            got = [v for pk, v in pins_cache.get(p, []) if norm_pkg(pk) == norm_pkg(s.get('package'))]
            if norm_ver(s.get('version')) not in [norm_ver(v) for v in got]:
                fails.append('T1 %s: %s pins %s at %s, the manifest says %s' % (
                    s.get('id'), p, s.get('package'), ', '.join(got) or 'nothing', s.get('version')))
            exp = s.get('expected') or {}
            if not exp.get('advisories') and not exp.get('advisories_not_established'):
                fails.append('T7 %s records no advisory id and no reason none is established' % s.get('id'))
    # T2
    declared = set()
    for s in seeds:
        if s.get('kind') == 'dependency':
            declared.add((norm_path(s.get('path')), norm_pkg(s.get('package')), norm_ver(s.get('version'))))
    for n in non:
        if not str(n.get('why') or '').strip():
            fails.append('T2 the non-seed pin %s %s in %s gives no reason' % (n.get('package'), n.get('version'), n.get('path')))
        declared.add((norm_path(n.get('path')), norm_pkg(n.get('package')), norm_ver(n.get('version'))))
    for rel, pins in sorted(pins_cache.items()):
        for pk, v in pins:
            if (rel, norm_pkg(pk), norm_ver(v)) not in declared:
                fails.append('T2 %s pins %s %s, which the manifest neither lists as a seed nor declares as a '
                             'non-seed pin: a new fixture dependency is evaluated on its own' % (rel, pk, v))
    for n in non:
        key = norm_path(n.get('path'))
        if not any(norm_pkg(pk) == norm_pkg(n.get('package')) and norm_ver(v) == norm_ver(n.get('version'))
                   for pk, v in pins_cache.get(key, [])):
            fails.append('T2 the non-seed pin %s %s is no longer in %s' % (n.get('package'), n.get('version'), key))
    # T4
    want = set(expected_signals(root))
    have = set((norm_path(s.get('path')), s.get('signal')) for s in seeds if s.get('signal'))
    for p, sig in sorted(want - have):
        fails.append('T4 EXPECTED_SIGNALS names %s for %s, and no seed carries it' % (sig, p))
    for p, sig in sorted(have - want):
        fails.append('T4 seed signal %s for %s is in no EXPECTED_SIGNALS.json' % (sig, p))
    # T5
    sp = os.path.join(root, seed_pins_rel)
    if os.path.isfile(sp):
        for pin in json.load(io.open(sp, encoding='utf-8')).get('seeds') or []:
            pkg, _, ver = str(pin.get('pin') or '').rpartition(' ')
            if (norm_path(pin.get('path')), norm_pkg(pkg), norm_ver(ver)) not in declared or not any(
                    s.get('kind') == 'dependency' and norm_path(s.get('path')) == norm_path(pin.get('path'))
                    and norm_pkg(s.get('package')) == norm_pkg(pkg) for s in seeds):
                fails.append('T5 SEED_PINS.json holds %s in %s, which is not a seed here' % (pin.get('pin'), pin.get('path')))
    else:
        fails.append('T5 %s is missing' % seed_pins_rel)
    return fails


def cmd_check(root):
    try:
        fails = check_tree(root)
        n = len(load_manifest(root)['seeds'])
    except Unreadable as exc:
        print('UNKNOWN: %s' % exc)
        return 2
    if fails:
        for f in fails:
            print('FAIL ' + f)
        print('::error title=Negative-test manifest drift::%d check(s) failed against %s.' % (len(fails), manifest_rel))
        return 1
    print('PASS: %d seed(s) in %s hold against the tree, SEED_PINS.json and every EXPECTED_SIGNALS.json; '
          'every fixture pin under tests/ is a seed or a declared non-seed pin.' % (n, manifest_rel))
    return 0


# ----------------------------------------------------------------------------- propose
def cmd_propose(root, trivy_path):
    try:
        doc = json.load(io.open(trivy_path, encoding='utf-8'))
    except (OSError, ValueError) as exc:
        print('UNKNOWN: %s' % exc)
        return 2
    base = norm_path(doc.get('ArtifactName') or 'tests/consumer-fixture')
    rows = {}
    for r in doc.get('Results') or []:
        for v in r.get('Vulnerabilities') or []:
            key = (base + '/' + norm_path(r.get('Target')), v.get('PkgName'), v.get('InstalledVersion'))
            ghsa = sorted(set(re.findall(r'GHSA-[a-z0-9]{4}-[a-z0-9]{4}-[a-z0-9]{4}', json.dumps(v))) - {v.get('VulnerabilityID')})
            rows.setdefault(key, []).append({'id': v.get('VulnerabilityID'), 'aliases': ghsa,
                                             'severity': v.get('Severity')})
    print(json.dumps([{'path': k[0], 'package': k[1], 'version': k[2],
                       'advisories': sorted(a, key=lambda x: x['id'])} for k, a in sorted(rows.items())], indent=1))
    return 0


